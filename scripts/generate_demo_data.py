"""Generate the frontend's synthetic demonstration data by running the REAL engine.

    .\\.venv\\Scripts\\python.exe scripts\\generate_demo_data.py

Why run the real engine instead of writing JSON by hand: the demo fixtures then have exactly
the shape and realism of real API responses, and cannot drift from the backend contract.

Privacy: the passwords below are fabricated (common patterns plus seeded-random strings).
Only the engine's *results* are written; the engine never includes the password in a result,
and this script asserts that none of them appears in the output.

Output (committed): frontend/src/demo/demoData.json - always labelled "Demo data" in the UI.
"""

from __future__ import annotations

import json
import random
import string
import sys
from pathlib import Path

from fastapi.testclient import TestClient

from passaudit.config import Settings
from passaudit.main import create_app

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "src" / "demo" / "demoData.json"

# --- fabricated passwords ---------------------------------------------------------------
LEAKED = [
    "password1",
    "letmein",
    "qwerty123",
    "iloveyou",
    "dragon",
    "monkey123",
    "abc12345",
    "welcome1",
    "admin123",
    "football",
]
SEASONAL = [
    "Summer2024!",
    "Winter#2023",
    "Spring2025",
    "Autumn!2022",
    "Company2025",
    "Welcome2024!",
    "January2025",
    "Passw0rd!",
    "Acme@2024",
    "Sunshine99",
]
PASSPHRASES = [
    "correct horse battery staple",
    "purple-monkey-dishwasher-42",
    "blue tractor sings loudly",
    "my cat eats ripe mango daily",
    "trainstationcoffee",
    "Orbit-Lantern-Quartz-Maple",
]
PATTERNS = ["qwertyuiop", "1qaz2wsx3edc", "abcdef123456", "aaaaaaaaaa", "123456789012"]


def random_strong(rng: random.Random, length: int) -> str:
    alphabet = string.ascii_letters + string.digits + "!#$%&*+-=?@^_"
    return "".join(rng.choice(alphabet) for _ in range(length))


def build_batch() -> list[tuple[str, str]]:
    rng = random.Random(20261126)  # noqa: S311 - reproducible demo data, not security
    passwords: list[str] = []
    passwords += LEAKED
    passwords += SEASONAL
    passwords += PASSPHRASES
    passwords += PATTERNS
    passwords += [random_strong(rng, rng.randint(14, 22)) for _ in range(9)]
    passwords += ["letmein", "Summer2024!", "iloveyou", "Summer2024!"]  # deliberate reuse
    rng.shuffle(passwords)
    departments = ["finance", "engineering", "support", "sales", "hr", "ops"]
    return [(f"{rng.choice(departments)}-{i:03d}", pw) for i, pw in enumerate(passwords, start=1)]


def main() -> int:
    client = TestClient(create_app(Settings(_env_file=None, env="test", rate_limit_enabled=False)))
    batch = build_batch()
    secrets_used = [pw for _, pw in batch]

    analyses = []
    samples = [
        ("weak", "Weak: a common word with a year", "Summer2024!", "online_account"),
        ("medium", "Medium: a short passphrase", "blue tractor sings loudly", "online_account"),
        (
            "strong",
            "Strong: random characters",
            random_strong(random.Random(7), 18),  # noqa: S311 - reproducible demo data
            "privileged_account",
        ),
    ]
    for key, title, password, usage in samples:
        secrets_used.append(password)
        response = client.post(
            "/api/v1/audit", json={"password": password, "context": {"usage": usage}}
        )
        response.raise_for_status()
        analyses.append({"id": key, "title": title, "usage": usage, "analysis": response.json()})

    batch_resp = client.post(
        "/api/v1/audit/batch",
        json={"items": [{"id": i, "password": p} for i, p in batch], "detail": "summary"},
    )
    batch_resp.raise_for_status()

    policy_resp = client.post(
        "/api/v1/policy/validate",
        json={
            "password": "Summer2024!",
            "policy": {
                "min_length": 14,
                "min_uppercase": 1,
                "min_digits": 1,
                "min_symbols": 1,
                "max_repeat_run": 3,
                "min_strength_score": 3,
            },
        },
    )
    policy_resp.raise_for_status()

    data = {
        "_comment": "SYNTHETIC DEMO DATA generated by scripts/generate_demo_data.py from "
        "fabricated "
        "passwords via the real engine. Not derived from any real password.",
        "engine_version": analyses[0]["analysis"]["version"],
        "analyses": analyses,
        "batch": batch_resp.json(),
        "policyCheck": {
            "policy": {
                "min_length": 14,
                "min_uppercase": 1,
                "min_digits": 1,
                "min_symbols": 1,
                "max_repeat_run": 3,
                "min_strength_score": 3,
            },
            "result": policy_resp.json(),
        },
    }
    text = json.dumps(data, indent=1, ensure_ascii=True) + "\n"
    for secret in secrets_used:
        if len(secret) >= 6 and secret in text:
            sys.stderr.write("LEAK: a password appears in the output; aborting\n")
            return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    summary = data["batch"]["summary"]
    sys.stdout.write(
        f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KiB): "
        f"{data['batch']['count']} entries, "
        f"risk levels {summary['risk_levels']}, reused {summary['reused_in_batch']}\n"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
